
import React, { useState } from "react";
import ErrorBoundary from "./ErrorBoundary";
import "./App.css";

function Child() {
  const [error, setError] = useState(false);

  if (error) {
    throw new Error("Error generated by button click!");
  }

  return (
    <div className="box">
      <h2>Child Component</h2>
      <p>Click the button to generate an error.</p>
      <button onClick={() => setError(true)}>
        Throw Error
      </button>
    </div>
  );
}

function App() {
  const [key, setKey] = useState(0);

  return (
    <div className="container">
      <h1>Error Boundary Example</h1>

      <ErrorBoundary
        key={key}
        onRetry={() => setKey((prev) => prev + 1)}
      >
        <Child />
      </ErrorBoundary>
    </div>
  );
}

export default App;
